// MARK: - Workout Session DTO
// Exercise logs (sets/reps/weight) are local-only in V1; only session metadata is synced.

struct WorkoutSessionDTO: Codable {
    var id: String
    var userId: String
    var startedAt: String
    var endedAt: String?
    var workoutGoal: String
    var title: String
    var notes: String?
    var totalEnergyKilocalories: Double?
    var durationSeconds: Double?
    var isCompleted: Bool
    var perceivedExertionLevel: Int?
    var source: String

    enum CodingKeys: String, CodingKey {
        case id
        case userId                  = "user_id"
        case startedAt               = "started_at"
        case endedAt                 = "ended_at"
        case workoutGoal             = "workout_goal"
        case title
        case notes
        case totalEnergyKilocalories = "total_energy_kilocalories"
        case durationSeconds         = "duration_seconds"
        case isCompleted             = "is_completed"
        case perceivedExertionLevel  = "perceived_exertion_level"
        case source
    }

    init(from session: WorkoutSession, userId: String) {
        let iso = ISO8601DateFormatter()
        self.id                      = session.id.uuidString
        self.userId                  = userId
        self.startedAt               = iso.string(from: session.startedAt)
        self.endedAt                 = session.endedAt.map { iso.string(from: $0) }
        self.workoutGoal             = session.workoutGoalRawValue
        self.title                   = session.title
        self.notes                   = session.notes
        self.totalEnergyKilocalories = session.totalEnergyKilocalories
        self.durationSeconds         = session.durationSeconds
        self.isCompleted             = session.isCompleted
        self.perceivedExertionLevel  = session.perceivedExertionLevel
        self.source                  = session.source
    }
}
