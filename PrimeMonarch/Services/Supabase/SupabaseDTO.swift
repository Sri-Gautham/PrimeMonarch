import Foundation

// Codable types that mirror Supabase table columns (snake_case).
// No Supabase SDK import needed — pure Foundation.
// See supabase/schema.sql for the corresponding table definitions.

// MARK: - User Profile DTO

struct UserProfileDTO: Codable {
    var id: String              // = Supabase auth user UUID (primary key)
    var displayName: String?
    var dateOfBirth: String?    // ISO-8601 full-date: "YYYY-MM-DD"
    var biologicalSex: String?
    var heightCm: Double?
    var currentWeightKg: Double?
    var targetWeightKg: Double?
    var preferredWeightUnit: String
    var preferredDistanceUnit: String
    var onboardingCompleted: Bool
    var onboardingStep: Int
    var updatedAt: String?

    enum CodingKeys: String, CodingKey {
        case id
        case displayName           = "display_name"
        case dateOfBirth           = "date_of_birth"
        case biologicalSex         = "biological_sex"
        case heightCm              = "height_cm"
        case currentWeightKg       = "current_weight_kg"
        case targetWeightKg        = "target_weight_kg"
        case preferredWeightUnit   = "preferred_weight_unit"
        case preferredDistanceUnit = "preferred_distance_unit"
        case onboardingCompleted   = "onboarding_completed"
        case onboardingStep        = "onboarding_step"
        case updatedAt             = "updated_at"
    }

    init(from profile: UserProfile, userId: String) {
        let iso = ISO8601DateFormatter()
        iso.formatOptions = [.withFullDate]
        self.id                    = userId
        self.displayName           = profile.displayName
        self.dateOfBirth           = profile.dateOfBirth.map { iso.string(from: $0) }
        self.biologicalSex         = profile.biologicalSexRawValue
        self.heightCm              = profile.heightCentimeters
        self.currentWeightKg       = profile.currentWeightKilograms
        self.targetWeightKg        = profile.targetWeightKilograms
        self.preferredWeightUnit   = profile.preferredWeightUnitRawValue
        self.preferredDistanceUnit = profile.preferredDistanceUnitRawValue
        self.onboardingCompleted   = profile.onboardingCompleted
        self.onboardingStep        = profile.onboardingStep
        self.updatedAt             = ISO8601DateFormatter().string(from: profile.updatedAt)
    }
}

